function pack(type, rows, animation) {
  return rows.map(([title, description, emoji = "🔮", delta = 0], index) =>
    Object.freeze({
      id: `${type}-${String(index + 1).padStart(3, "0")}`,
      type,
      title,
      description,
      emoji,
      delta,
      animation:
        type === "chaos"
          ? ["shake", "slide", "spin", "glitch", "pop", "float"][index % 6]
          : animation,
    }),
  );
}
